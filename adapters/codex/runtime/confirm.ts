/**
 * Codex native confirmation channel declaration (closure design §5.1,
 * appendix K.2).
 *
 * 0.160.1 renders a stdio MCP server's `elicitation/create` request in its TUI
 * (`McpServerElicitationOverlay`), both during a tool call and at idle, and
 * returns the user's selection to the server. The command hook only allows
 * allow/deny, so the MCP form is the confirmation surface.
 *
 * The range is the adapter's verified compatibility interval (appendix A.1);
 * outside it the channel stays silent and the capability stays unknown.
 */

import type { McpConfirmHostSpec } from "@evoplug/host-runtime";

export const CODEX_MCP_CONFIRM_FLAG = "--mcp-confirm";

export const CODEX_CONFIRM_SPEC: McpConfirmHostSpec = Object.freeze({
  host_id: "codex",
  server_name: "evoplug_confirm",
  mechanism: "mcp_elicitation",
  supported_range: ">=0.160.1 <0.170.0",
  carrier_event: "UserPromptSubmit"
});

/**
 * Absolute-path profile writer (closure design appendix J.5, K.2).
 *
 * Attach cannot expand a placeholder inside a `whole_file` TOML target, and
 * Codex does not pass `CODEX_HOME` to MCP children, so a profile that points at
 * `$HOME/.codex` only works for the default layout. The runtime knows its own
 * absolute entry and artifact root, so on each hook run it (re)writes the
 * evoplug-owned profile with the exact absolute node and entry paths plus the
 * variables the server needs. The file is registered by attach, written
 * 0600/atomically, and never touches Codex's own `config.toml`.
 */

import { chmodSync, existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

/** `$CODEX_HOME/hooks/evoplug` -> `$CODEX_HOME/evoplug-confirm.config.toml`. */
export function confirmProfilePath(artifactRoot: string): string | null {
  const normalized = artifactRoot.replace(/\/+$/u, "");
  const suffix = "/hooks/evoplug";
  if (!normalized.endsWith(suffix)) return null;
  const codexHome = normalized.slice(0, normalized.length - suffix.length);
  if (codexHome.length === 0) return null;
  return join(codexHome, "evoplug-confirm.config.toml");
}

function tomlString(value: string): string {
  return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

export function renderConfirmProfile(input: {
  readonly node: string;
  readonly entry: string;
  readonly evoplug_home: string | null;
}): string {
  const env: string[] = ['EVOPLUG_MCP_CONFIRM = "1"'];
  if (input.evoplug_home !== null) {
    env.push(`EVOPLUG_HOME = ${tomlString(input.evoplug_home)}`);
  }
  return [
    "# Evoplug native confirmation channel (stdio MCP).",
    "# Generated by the Evoplug runtime; attach owns this path.",
    "# Loaded with: codex -p evoplug-confirm",
    "check_for_update_on_startup = false",
    "",
    "[mcp_servers.evoplug_confirm]",
    `command = ${tomlString(input.node)}`,
    `args = [${tomlString(input.entry)}, "--mcp-confirm"]`,
    `env = { ${env.join(", ")} }`,
    ""
  ].join("\n");
}

/**
 * Writes the profile only when its content would change. Returns the path when
 * the profile is present and current, `null` when the artifact root is not the
 * Codex runtime layout or the write failed.
 */
export function ensureConfirmProfile(input: {
  readonly artifact_root: string;
  readonly entry: string;
  readonly node: string;
  readonly evoplug_home: string | null;
  readonly disabled?: boolean;
}): string | null {
  if (input.disabled === true) return null;
  const path = confirmProfilePath(input.artifact_root);
  if (path === null) return null;
  const content = renderConfirmProfile(input);
  try {
    if (existsSync(path)) {
      const current = readFileSync(path, "utf8");
      if (current === content) return path;
    }
    mkdirSync(dirname(path), { recursive: true, mode: 0o700 });
    const temporary = `${path}.${String(process.pid)}.tmp`;
    writeFileSync(temporary, content, { mode: 0o600 });
    chmodSync(temporary, 0o600);
    renameSync(temporary, path);
    return path;
  } catch {
    return null;
  }
}
