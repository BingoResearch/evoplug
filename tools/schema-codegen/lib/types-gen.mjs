// JSON Schema 2020-12 -> TypeScript declaration generator.
//
// Supported subset (everything the evoplug boundary schemas use):
//   $ref to #/$defs, type (single or union), enum, const, object properties,
//   required, additionalProperties (false or schema), array items/prefixItems,
//   oneOf, anyOf, allOf, boolean schemas, title-named subschemas.
// The generator fails closed on anything it cannot express exactly.

import { fail } from "./utils.mjs";

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

export function generateTypesModule(entry) {
  const { schema, relative, sourceHash } = entry;
  const named = new Map();
  const order = [];
  const rootName = schema.title;

  collectNamed(schema, named, order, true);
  rootNameCheck(rootName, relative);

  const declarations = [renderDeclaration(rootName, schema, relative)];
  for (const name of order) {
    if (name === rootName) continue;
    const node = named.get(name);
    declarations.push(renderDeclaration(name, node, relative));
  }

  const header = [
    "// DO NOT EDIT. Generated by tools/schema-codegen/cli.mjs.",
    `// Source: ${relative}`,
    `// source-sha256: ${sourceHash}`,
    `// schema-id: ${schema.$id}`,
    "",
    "/* eslint-disable */",
    "",
  ].join("\n");

  const body = declarations.join("\n\n");
  const prelude =
    body.includes("JsonValue") && !named.has("JsonValue")
      ? [
          "export type JsonValue =",
          "  | string",
          "  | number",
          "  | boolean",
          "  | null",
          "  | readonly JsonValue[]",
          "  | { readonly [key: string]: JsonValue };",
          "",
        ].join("\n")
      : "";
  return `${header}${prelude}${body}\n`;
}

function rootNameCheck(name, file) {
  if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) {
    fail(`${file}: root title "${name}" must be PascalCase`);
  }
}

function collectNamed(node, named, order, root) {
  if (node === null || typeof node !== "object") return;
  if (Array.isArray(node)) {
    for (const child of node) collectNamed(child, named, order, false);
    return;
  }
  if (!root && typeof node.title === "string") {
    if (!named.has(node.title)) {
      named.set(node.title, node);
      order.push(node.title);
    }
  }
  if (node.$defs && typeof node.$defs === "object") {
    for (const [key, def] of Object.entries(node.$defs)) {
      if (!named.has(key)) {
        named.set(key, def);
        order.push(key);
      }
    }
  }
  for (const [key, value] of Object.entries(node)) {
    if (key === "default" || key === "examples" || key === "enum" || key === "const") continue;
    if (key === "$defs") continue;
    collectNamed(value, named, order, false);
  }
}

function renderDeclaration(name, node, file) {
  const doc = docComment(node);
  if (isObjectLike(node) && !hasUnion(node)) {
    const body = renderObjectBody(node, file);
    if (body === "Record<string, never>") {
      return `${doc}export type ${name} = Record<string, never>;`;
    }
    return `${doc}export interface ${name} ${body}`;
  }
  return `${doc}export type ${name} = ${renderType(node, file, name)};`;
}

function docComment(node) {
  if (typeof node.description !== "string" || node.description.length === 0) return "";
  const text = node.description.replace(/\*\//g, "*\\/");
  return `/** ${text} */\n`;
}

function hasUnion(node) {
  return node.oneOf !== undefined || node.anyOf !== undefined || node.allOf !== undefined;
}

function isObjectLike(node) {
  if (typeof node !== "object" || node === null || Array.isArray(node)) return false;
  if (node.$ref !== undefined || node.enum !== undefined || node.const !== undefined) return false;
  if (node.oneOf !== undefined || node.anyOf !== undefined || node.allOf !== undefined) return false;
  if (node.type === "object") return true;
  if (Array.isArray(node.type)) return false;
  return node.properties !== undefined || node.required !== undefined;
}

function renderType(node, file, contextName) {
  if (node === true) return "JsonValue";
  if (node === false) return "never";
  if (typeof node !== "object" || node === null || Array.isArray(node)) {
    fail(`${file}: invalid schema node inside ${contextName}`);
  }
  const meaningfulKeys = Object.keys(node).filter(
    (key) => !["title", "description", "$comment", "default", "examples"].includes(key),
  );
  if (meaningfulKeys.length === 0) return "JsonValue";
  if (node.title !== undefined && node.title !== contextName && !node.properties && !node.enum && node.const === undefined && !node.type) {
    // Named union alias already emitted by collectNamed.
    return node.title;
  }
  if (node.$ref !== undefined) {
    if (!node.$ref.startsWith("#/$defs/")) fail(`${file}: non-local $ref ${node.$ref}`);
    return node.$ref.slice("#/$defs/".length);
  }
  if (node.const !== undefined) return literal(node.const, file);
  if (node.enum !== undefined) {
    if (!Array.isArray(node.enum) || node.enum.length === 0) fail(`${file}: empty enum`);
    return node.enum.map((value) => literal(value, file)).join(" | ");
  }
  if (node.oneOf !== undefined) return unionOf(node.oneOf, file, contextName);
  if (node.anyOf !== undefined) return unionOf(node.anyOf, file, contextName);
  if (node.allOf !== undefined) {
    const parts = node.allOf.map((part) => parenthesize(renderType(part, file, contextName)));
    if (parts.length === 0) return "never";
    return parts.join(" & ");
  }
  if (Array.isArray(node.type)) {
    const parts = node.type.map((type) => renderPrimitive(type, node, file, contextName));
    return unique(parts).join(" | ");
  }
  if (node.type !== undefined) {
    return renderPrimitive(node.type, node, file, contextName);
  }
  if (node.properties !== undefined || node.required !== undefined) {
    return renderObjectBody(node, file);
  }
  if (node.items !== undefined || node.prefixItems !== undefined) {
    return renderArray(node, file, contextName);
  }
  if (node.not !== undefined) fail(`${file}: "not" is not representable in TypeScript`);
  fail(`${file}: cannot derive a TypeScript type for ${contextName}`);
}

function unionOf(parts, file, contextName) {
  if (!Array.isArray(parts) || parts.length === 0) fail(`${file}: empty union in ${contextName}`);
  const rendered = parts.map((part) => parenthesize(renderType(part, file, contextName)));
  return unique(rendered).join(" | ");
}

function parenthesize(type) {
  return type.includes(" & ") ? `(${type})` : type;
}

function unique(values) {
  return [...new Set(values)];
}

function renderPrimitive(type, node, file, contextName) {
  switch (type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "object":
      return renderObjectBody(node, file);
    case "array":
      return renderArray(node, file, contextName);
    default:
      fail(`${file}: unsupported type "${type}" in ${contextName}`);
  }
}

function renderArray(node, file, contextName) {
  const items = node.items ?? node.prefixItems;
  if (items === undefined) fail(`${file}: array without items in ${contextName}`);
  if (Array.isArray(items)) {
    const tuple = items.map((item) => renderType(item, file, contextName));
    return `readonly [${tuple.join(", ")}]`;
  }
  return `readonly (${renderType(items, file, contextName)})[]`;
}

function renderObjectBody(node, file) {
  const properties = node.properties ?? {};
  const required = new Set(Array.isArray(node.required) ? node.required : []);
  const fields = [];
  for (const [key, propertySchema] of Object.entries(properties)) {
    const optional = required.has(key) ? "" : "?";
    const propName = IDENTIFIER.test(key) ? key : JSON.stringify(key);
    const propertyType = indentType(renderType(propertySchema, file, key), 2);
    fields.push(`${docIndent(propertySchema)}readonly ${propName}${optional}: ${propertyType};`);
  }
  const additional = node.additionalProperties;
  if (additional !== undefined) {
    if (additional === false) {
      // no index signature
    } else if (additional === true) {
      fields.push("readonly [key: string]: JsonValue;");
    } else {
      if (fields.length > 0) {
        fail(`${file}: an object with both properties and an additionalProperties schema is not representable`);
      }
      fields.push(`readonly [key: string]: ${renderType(additional, file, "additionalProperties")};`);
    }
  }
  if (fields.length === 0) return "Record<string, never>";
  return `{\n${fields.map((field) => `  ${field}`).join("\n")}\n}`;
}

function docIndent(schema) {
  if (typeof schema !== "object" || schema === null || typeof schema.description !== "string") return "";
  const text = schema.description.replace(/\*\//g, "*\\/");
  return `/** ${text} */ `;
}

function indentType(type, spaces) {
  if (!type.includes("\n")) return type;
  const pad = " ".repeat(spaces);
  return type
    .split("\n")
    .map((line, index) => (index === 0 ? line : `${pad}${line}`))
    .join("\n");
}

function literal(value, file) {
  if (value === null) return "null";
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number" && Number.isFinite(value)) return String(value);
  if (typeof value === "boolean") return String(value);
  if (Array.isArray(value)) {
    return `readonly [${value.map((item) => literal(item, file)).join(", ")}]`;
  }
  if (typeof value === "object") {
    const entries = Object.entries(value);
    if (entries.length === 0) return "Record<string, never>";
    const fields = entries.map(([key, item]) => {
      const propName = IDENTIFIER.test(key) ? key : JSON.stringify(key);
      return `readonly ${propName}: ${literal(item, file)};`;
    });
    return `{\n${fields.map((field) => `  ${field}`).join("\n")}\n}`;
  }
  fail(`${file}: unsupported literal ${JSON.stringify(value)}`);
}
