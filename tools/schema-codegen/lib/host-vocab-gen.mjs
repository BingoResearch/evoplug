// Generates packages/core/src/generated/host-vocabulary.ts from the HOST
// primitive vocabulary schema. HOST owns the vocabulary; this generator only
// projects it into the shared core module (DD-FND-030, DD-CAP-001).

import { fail, sha256Text } from "./utils.mjs";

export function generateHostVocabularyModule(entry) {
  const schema = entry.schema;
  const vocab = schema["x-evoplug-vocabulary"];
  if (!vocab || typeof vocab !== "object") {
    fail(`${entry.relative}: missing x-evoplug-vocabulary`);
  }
  const required = [
    "host_ids",
    "host_modes",
    "capability_statuses",
    "evidence_stages",
    "host_probe_results",
    "capability_subjects",
    "host_version_kinds",
    "execution_environments",
  ];
  for (const key of required) {
    if (!Array.isArray(vocab[key]) || vocab[key].length === 0) {
      fail(`${entry.relative}: x-evoplug-vocabulary.${key} must be a non-empty array`);
    }
  }
  const typeFor = {
    host_ids: "HostId",
    host_modes: "HostMode",
    capability_statuses: "CapabilityStatus",
    evidence_stages: "EvidenceStage",
    host_probe_results: "HostProbeResult",
    capability_subjects: "CapabilitySubject",
    host_version_kinds: "HostVersionKind",
    execution_environments: "ExecutionEnvironmentKind",
  };
  const constFor = {
    host_ids: "HOST_IDS",
    host_modes: "HOST_MODES",
    capability_statuses: "CAPABILITY_STATUSES",
    evidence_stages: "EVIDENCE_STAGES",
    host_probe_results: "HOST_PROBE_RESULTS",
    capability_subjects: "CAPABILITY_SUBJECTS",
    host_version_kinds: "HOST_VERSION_KINDS",
    execution_environments: "EXECUTION_ENVIRONMENT_KINDS",
  };
  const checkFor = {
    host_ids: "isHostId",
    host_modes: "isHostMode",
    capability_statuses: "isCapabilityStatus",
    evidence_stages: "isEvidenceStage",
    host_probe_results: "isHostProbeResult",
    capability_subjects: "isCapabilitySubject",
  };

  const lines = [
    "// DO NOT EDIT. Generated by tools/schema-codegen/cli.mjs.",
    `// Source: ${entry.relative}`,
    `// source-sha256: ${entry.sourceHash}`,
    `// schema-id: ${schema.$id}`,
    "// HOST owns this vocabulary; FND/CFG/REV/QP/EVD may only import it.",
    "",
    "/* eslint-disable */",
    "",
  ];
  for (const key of required) {
    const values = vocab[key];
    if (new Set(values).size !== values.length) fail(`${entry.relative}: duplicate value in ${key}`);
    lines.push(`export type ${typeFor[key]} =\n  | ${values.map((value) => JSON.stringify(value)).join("\n  | ")};`);
    lines.push("");
  }
  for (const key of required) {
    lines.push(`export const ${constFor[key]}: readonly ${typeFor[key]}[] = [${vocab[key]
      .map((value) => JSON.stringify(value))
      .join(", ")}];`);
    lines.push("");
  }
  for (const [key, fn] of Object.entries(checkFor)) {
    lines.push(`export function ${fn}(value: string): value is ${typeFor[key]} {`);
    lines.push(`  return (${constFor[key]} as readonly string[]).includes(value);`);
    lines.push("}");
    lines.push("");
  }
  lines.push("export interface UnknownFact {");
  lines.push('  readonly kind: "unknown";');
  lines.push("  readonly reason_code: string;");
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

export function vocabularyHash(entry) {
  return sha256Text(JSON.stringify(entry.schema["x-evoplug-vocabulary"]));
}
