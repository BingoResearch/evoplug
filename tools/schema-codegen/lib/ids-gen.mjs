// Generates packages/core/src/generated/ids.ts and
// schemas/generated/id-prefix-registry.json from the single registry source.

import { fail, sha256Text, sortedJson } from "./utils.mjs";

const CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";

export function generateIdsModule(registry) {
  validateRegistry(registry);
  const entries = idEntries(registry);
  const active = entries.filter((entry) => entry.state === "active");
  const reserved = entries.filter((entry) => entry.state === "reserved");
  const prefixUnion = entries.map((entry) => JSON.stringify(entry.prefix)).join("\n  | ");
  const contentPrefixes = registry.content_key_prefixes ?? [];
  if (contentPrefixes.length === 0) fail("id-prefix-registry: content_key_prefixes must not be empty");
  const contentUnion = contentPrefixes
    .map((entry) => JSON.stringify(entry.prefix))
    .join("\n  | ");
  const hashPrefixes = registry.hash_id_prefixes ?? [];
  const hashPrefixUnion = hashPrefixes.length === 0
    ? "never"
    : hashPrefixes.map((entry) => JSON.stringify(entry.prefix)).join("\n  | ");

  const lines = [
    "// DO NOT EDIT. Generated by tools/schema-codegen/cli.mjs.",
    "// Source: schemas/common/id-prefix-registry.json",
    "// source-sha256: " + sha256Text(JSON.stringify(sortedJson(normalizedRegistry(registry)))),
    "",
    "/* eslint-disable */",
    'import { randomBytes } from "node:crypto";',
    "",
    "export type Ulid = string & { readonly __ulid: unique symbol };",
    "",
    `export type IdPrefix =\n  | ${prefixUnion};`,
    "",
    `export type ContentKeyPrefix =\n  | ${contentUnion};`,
    "",
    `/** Hash-derived ids of the form \`<prefix>:<64 lowercase hex>\`. */`,
    `export type HashIdPrefix = ${hashPrefixUnion};`,
    "",
    'export type HashId<P extends HashIdPrefix = HashIdPrefix> = `${P}:${string}`;',
    "",
    'export type ContentKey<P extends ContentKeyPrefix = ContentKeyPrefix> = `${P}:${string}`;',
    'export type Hash = `sha256:${string}`;',
    'export type Id<P extends IdPrefix = IdPrefix> = `${P}:${Ulid}`;',
    "",
    "/** Prefixes that may be minted by newId. Reserved prefixes are rejected. */",
    `export const ID_PREFIXES: readonly IdPrefix[] = [${active
      .map((entry) => JSON.stringify(entry.prefix))
      .join(", ")}];`,
    "",
    `export const RESERVED_ID_PREFIXES: readonly IdPrefix[] = [${reserved
      .map((entry) => JSON.stringify(entry.prefix))
      .join(", ")}];`,
    "",
    `export const CONTENT_KEY_PREFIXES: readonly ContentKeyPrefix[] = [${contentPrefixes
      .map((entry) => JSON.stringify(entry.prefix))
      .join(", ")}];`,
    "",
    `export const HASH_ID_PREFIXES: readonly HashIdPrefix[] = [${hashPrefixes
      .map((entry) => JSON.stringify(entry.prefix))
      .join(", ")}];`,
    "",
    "const ULID_PATTERN = /^[0-9A-HJKMNP-TV-Z]{26}$/;",
    "const HASH_PATTERN = /^sha256:[0-9a-f]{64}$/;",
    "const CROCKFORD_ALPHABET = " + JSON.stringify(CROCKFORD) + ";",
    "",
    "let lastTime = -1;",
    "let lastRandom = 0n;",
    "const RANDOM_LIMIT = 1n << 80n;",
    "",
    "function encodeTime(time: number): string {",
    "  let value = BigInt(time);",
    "  let out = \"\";",
    "  for (let index = 0; index < 10; index += 1) {",
    "    out = CROCKFORD_ALPHABET[Number(value & 31n)] + out;",
    "    value >>= 5n;",
    "  }",
    "  return out;",
    "}",
    "",
    "function encodeRandom(random: bigint): string {",
    "  let value = random;",
    "  let out = \"\";",
    "  for (let index = 0; index < 16; index += 1) {",
    "    out = CROCKFORD_ALPHABET[Number(value & 31n)] + out;",
    "    value >>= 5n;",
    "  }",
    "  return out;",
    "}",
    "",
    "function random80(): bigint {",
    "  const bytes = randomBytes(10);",
    "  let value = 0n;",
    "  for (const byte of bytes) value = (value << 8n) | BigInt(byte);",
    "  return value & (RANDOM_LIMIT - 1n);",
    "}",
    "",
    "function hasPrefix(prefix: string): prefix is IdPrefix {",
    "  return (ID_PREFIXES as readonly string[]).includes(prefix);",
    "}",
    "",
    "export function isValidUlid(value: string): value is Ulid {",
    "  return typeof value === \"string\" && ULID_PATTERN.test(value);",
    "}",
    "",
    "export function isValidHash(value: string): value is Hash {",
    "  return typeof value === \"string\" && HASH_PATTERN.test(value);",
    "}",
    "",
    "export function isId<P extends IdPrefix>(value: string, prefix?: P): value is Id<P> {",
    "  if (typeof value !== \"string\") return false;",
    "  const separator = value.indexOf(\":\");",
    "  if (separator <= 0) return false;",
    "  const candidatePrefix = value.slice(0, separator);",
    "  if (!hasPrefix(candidatePrefix)) return false;",
    "  if (prefix !== undefined && candidatePrefix !== prefix) return false;",
    "  return ULID_PATTERN.test(value.slice(separator + 1));",
    "}",
    "",
    "export function parseId(value: string): { prefix: IdPrefix; ulid: Ulid } {",
    "  if (!isId(value)) {",
    "    const error = new RangeError(\"E_ID_PREFIX_UNKNOWN: not a registered prefix:ULID id\");",
    "    error.name = \"IdParseError\";",
    "    throw error;",
    "  }",
    "  const separator = value.indexOf(\":\");",
    "  const prefix = value.slice(0, separator);",
    "  if (!hasPrefix(prefix)) {",
    "    const error = new RangeError(\"E_ID_PREFIX_UNKNOWN: \" + prefix);",
    "    error.name = \"IdPrefixError\";",
    "    throw error;",
    "  }",
    "  return { prefix, ulid: value.slice(separator + 1) as Ulid };",
    "}",
    "",
    "export function newId<P extends IdPrefix>(prefix: P, now: number = Date.now()): Id<P> {",
    "  if (!hasPrefix(prefix)) {",
    "    const error = new RangeError(\"E_ID_PREFIX_UNKNOWN: \" + prefix);",
    "    error.name = \"IdPrefixError\";",
    "    throw error;",
    "  }",
    "  if (!Number.isSafeInteger(now) || now < 0 || now > 281474976710655) {",
    "    const error = new RangeError(\"E_SCHEMA: ULID timestamp out of range\");",
    "    error.name = \"IdTimestampError\";",
    "    throw error;",
    "  }",
    "  let random: bigint;",
    "  if (now === lastTime) {",
    "    lastRandom = (lastRandom + 1n) % RANDOM_LIMIT;",
    "    random = lastRandom;",
    "  } else {",
    "    lastTime = now;",
    "    random = random80();",
    "    lastRandom = random;",
    "  }",
    "  return `${prefix}:${encodeTime(now)}${encodeRandom(random)}` as Id<P>;",
    "}",
    "",
    "export function isContentKey<P extends ContentKeyPrefix>(value: string, prefix?: P): value is ContentKey<P> {",
    "  if (typeof value !== \"string\") return false;",
    "  const separator = value.indexOf(\":\");",
    "  if (separator <= 0) return false;",
    "  const candidatePrefix = value.slice(0, separator);",
    "  if (!(CONTENT_KEY_PREFIXES as readonly string[]).includes(candidatePrefix)) return false;",
    "  if (prefix !== undefined && candidatePrefix !== prefix) return false;",
    "  return /^[0-9a-f]{64}$/.test(value.slice(separator + 1));",
    "}",
    "",
  ];
  return lines.join("\n");
}

function validateRegistry(registry) {
  if (registry.schema_version !== "rsi.id_prefix_registry/1") {
    fail("id-prefix-registry: schema_version must be rsi.id_prefix_registry/1");
  }
  const entries = idEntries(registry);
  if (!Array.isArray(entries) || entries.length === 0) {
    fail("id-prefix-registry: prefixes must be non-empty");
  }
  const seen = new Set();
  for (const entry of entries) {
    for (const field of ["prefix", "owner", "object", "format", "since", "state"]) {
      if (typeof entry[field] !== "string" || entry[field].length === 0) {
        fail(`id-prefix-registry: entry ${JSON.stringify(entry)} misses ${field}`);
      }
    }
    if (!/^[a-z][a-z0-9]{0,15}$/.test(entry.prefix)) {
      fail(`id-prefix-registry: prefix "${entry.prefix}" must be lowercase ASCII`);
    }
    if (entry.format !== "ulid") fail(`id-prefix-registry: prefix "${entry.prefix}" format must be ulid`);
    if (entry.state !== "active" && entry.state !== "reserved") {
      fail(`id-prefix-registry: prefix "${entry.prefix}" state must be active|reserved`);
    }
    if (!/^\d{4}-\d{2}-\d{2}$/.test(entry.since)) fail(`id-prefix-registry: ${entry.prefix} since must be YYYY-MM-DD`);
    if (seen.has(entry.prefix)) fail(`id-prefix-registry: duplicate prefix "${entry.prefix}"`);
    seen.add(entry.prefix);
  }
  if (!Array.isArray(registry.content_key_prefixes) || registry.content_key_prefixes.length === 0) {
    fail("id-prefix-registry: content_key_prefixes must be non-empty");
  }
  // DD-FND-030: adapter and install-approval ids are mandatory registry rows.
  // A fixture that drops either one must fail at build time, not at runtime.
  const requiredOwners = new Map([
    ["adp", "host"],
    ["iap", "fnd"],
  ]);
  for (const [prefix, owner] of requiredOwners) {
    const entry = entries.find((candidate) => candidate.prefix === prefix);
    if (entry === undefined) {
      fail(`id-prefix-registry: required prefix "${prefix}" is missing`);
    }
    if (entry.owner !== owner) {
      fail(`id-prefix-registry: prefix "${prefix}" owner must be ${owner}`);
    }
  }
  for (const entry of registry.content_key_prefixes) {
    if (entry.prefix !== "propo") fail(`id-prefix-registry: only propo may be a ContentKey prefix`);
    if (seen.has(entry.prefix)) fail(`id-prefix-registry: ${entry.prefix} cannot be both Id and ContentKey`);
  }
  const hashPrefixes = registry.hash_id_prefixes ?? [];
  if (!Array.isArray(hashPrefixes)) fail("id-prefix-registry: hash_id_prefixes must be an array");
  const seenHash = new Set();
  for (const entry of hashPrefixes) {
    for (const field of ["prefix", "owner", "object", "format", "since", "state"]) {
      if (typeof entry[field] !== "string" || entry[field].length === 0) {
        fail(`id-prefix-registry: hash entry ${JSON.stringify(entry)} misses ${field}`);
      }
    }
    if (!/^[a-z][a-z0-9]{0,15}$/.test(entry.prefix)) {
      fail(`id-prefix-registry: hash prefix "${entry.prefix}" must be lowercase ASCII`);
    }
    if (entry.format !== "sha256") fail(`id-prefix-registry: hash prefix "${entry.prefix}" format must be sha256`);
    if (entry.state !== "active" && entry.state !== "reserved") {
      fail(`id-prefix-registry: hash prefix "${entry.prefix}" state must be active|reserved`);
    }
    if (!/^\d{4}-\d{2}-\d{2}$/.test(entry.since)) fail(`id-prefix-registry: ${entry.prefix} since must be YYYY-MM-DD`);
    if (seenHash.has(entry.prefix)) fail(`id-prefix-registry: duplicate hash prefix "${entry.prefix}"`);
    if (seen.has(entry.prefix)) fail(`id-prefix-registry: ${entry.prefix} cannot be both Id and HashId`);
    if (registry.content_key_prefixes.some((candidate) => candidate.prefix === entry.prefix)) {
      fail(`id-prefix-registry: ${entry.prefix} cannot be both ContentKey and HashId`);
    }
    seenHash.add(entry.prefix);
  }
}

export function normalizedRegistry(registry) {
  return {
    schema_version: registry.schema_version,
    prefixes: idEntries(registry),
    content_key_prefixes: registry.content_key_prefixes,
    hash_id_prefixes: registry.hash_id_prefixes ?? [],
  };
}

function idEntries(registry) {
  return registry.prefixes ?? registry.entries ?? [];
}
